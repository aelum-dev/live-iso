-- DMS user keybind overrides (edit via Control Center or dms; do not remove this header)

hl.unbind("SUPER + M")
hl.bind("SUPER + M", hl.dsp.exec_cmd("dms ipc call notepad toggle"), { description = "Notepad: Toggle" })
hl.unbind("ALT + Tab")
hl.bind("ALT + Tab", hl.dsp.focus({ workspace = "previous" }), { description = "Previous Visited Workspace" })
hl.unbind("SUPER + ALT + Left")
hl.bind("SUPER + ALT + Left", hl.dsp.focus({ workspace = "e-1" }), { description = "Previous Open Workspace" })
hl.unbind("SUPER + ALT + Right")
hl.bind("SUPER + ALT + Right", hl.dsp.focus({ workspace = "e+1" }), { description = "Next Open Workspace" })
hl.unbind("SUPER + mouse_down")
hl.bind("SUPER + mouse_down", hl.dsp.focus({ workspace = "e+1" }), { description = "Next Open Workspace" })
hl.unbind("SUPER + mouse_up")
hl.bind("SUPER + mouse_up", hl.dsp.focus({ workspace = "e-1" }), { description = "Previous Open Workspace" })
hl.unbind("mouse:275")
hl.bind("mouse:275", hl.dsp.focus({ workspace = "previous" }), { description = "Prev Workspace" })
hl.unbind("SUPER + F")
hl.bind("SUPER + F", hl.dsp.exec_cmd("nautilus --new-window"))
hl.unbind("SUPER + B")
hl.bind("SUPER + B", hl.dsp.exec_cmd("firefox"))
hl.unbind("SUPER + Return")
hl.bind("SUPER + Return", hl.dsp.exec_cmd("alacritty"), { description = "alacritty" })
hl.unbind("SUPER + XF86AudioLowerVolume")
hl.bind("SUPER + XF86AudioLowerVolume", hl.dsp.exec_cmd("wpctl set-volume @DEFAULT_AUDIO_SINK@ 0.1-"), { description = "Volume boost lower" })
hl.unbind("SUPER + XF86AudioRaiseVolume")
hl.bind("SUPER + XF86AudioRaiseVolume", hl.dsp.exec_cmd("wpctl set-volume @DEFAULT_AUDIO_SINK@ 0.1+"), { description = "Volume boost up" })
hl.unbind("ALT + SUPER + mouse_right")
hl.unbind("SUPER + I")
hl.unbind("SUPER + Page_Down")
hl.unbind("SUPER + Page_Up")
hl.unbind("SUPER + T")
hl.bind("SUPER + T", hl.dsp.window.float({ action = "toggle" }), { description = "Toggle Floating" })
hl.unbind("SUPER + U")
