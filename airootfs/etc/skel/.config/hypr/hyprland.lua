-- Input method (Fcitx5). The IM module selectors for Qt and XWayland clients;
-- the daemon itself is started by aelum-fcitx5.service, a user unit pulled into
-- the session by the seeded hyprland-session.target.wants link, and the package's
-- own XDG autostart entry is hidden in /etc/skel so that unit is the only owner.
-- The dbus-update-activation-environment call below propagates these variables
-- to D-Bus-activated clients.
--
-- Alt+Shift switches input methods and the framework owns that key. It lists
-- English first and the language of the location second
-- (/etc/xdg/fcitx5/profile, written by the installer from the two wizard
-- answers), and a keyboard layout is an input method to it — the framework has a
-- "keyboard-<layout>" entry for every xkeyboard-config layout — so one key
-- covers layouts and engines alike. There is deliberately no kb_options here:
-- grp:alt_shift_toggle would change the compositor's layout on the same press,
-- and one key press would move two things at once.
--
-- GTK_IM_MODULE is deliberately NOT set. Hyprland implements the Wayland
-- input-method protocol, so a native GTK3/GTK4 client composes through it
-- without a module — measured on an installed system: Pinyin preedit and the
-- candidate window worked in GNOME Text Editor (GTK4) and in Firefox's URL bar
-- (GTK3) with the variable unset, and fcitx5 itself posts a first-login
-- advisory asking for exactly this. Qt is the opposite case: its Wayland
-- text-input-v2 exists only in KWin, so QT_IM_MODULE stays, and XMODIFIERS
-- stays for everything running under XWayland.
hl.env("QT_IM_MODULE", "fcitx")
hl.env("XMODIFIERS", "@im=fcitx")

-- DMS_STARTUP_BEGIN
hl.on("hyprland.start", function()
	hl.exec_cmd("dbus-update-activation-environment --systemd --all")
	-- dms.service cannot be started by name (Requisite=graphical-session.target): start the seeded target.
	hl.exec_cmd("systemctl --user start hyprland-session.target")
end)
-- DMS_STARTUP_END

