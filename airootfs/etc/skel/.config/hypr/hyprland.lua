hl.config({ autogenerated = false })

-- DMS_STARTUP_BEGIN
hl.on("hyprland.start", function()
	hl.exec_cmd("dbus-update-activation-environment --systemd --all")
	-- dms.service is PartOf/Requisite=graphical-session.target in 2.0, so it cannot
	-- be started by name: the session target has to be up first. The seeded
	-- hyprland-session.target pulls graphical-session.target in and wants dms.service.
	hl.exec_cmd("systemctl --user start hyprland-session.target")
end)
-- DMS_STARTUP_END

